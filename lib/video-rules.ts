export type VideoRulesBlock =
  | { type: "title"; text: string }
  | { type: "heading"; text: string }
  | { type: "paragraph"; text: string }
  | { type: "list"; items: string[] };

/** 화면용으로만 나누기 — 글자 내용은 그대로 둔다. */
export function parseVideoRulesDocument(raw: string): VideoRulesBlock[] {
  const lines = raw.replace(/\r\n/g, "\n").split("\n");
  const blocks: VideoRulesBlock[] = [];
  let listItems: string[] = [];

  function flushList() {
    if (listItems.length === 0) return;
    blocks.push({ type: "list", items: listItems });
    listItems = [];
  }

  for (const line of lines) {
    const trimmed = line.trimEnd();
    if (!trimmed.trim()) {
      flushList();
      continue;
    }

    const titleMatch = trimmed.match(/^\[(.+)\]\s*$/);
    if (titleMatch && blocks.length === 0) {
      flushList();
      blocks.push({ type: "title", text: titleMatch[1] });
      continue;
    }

    const headingMatch = trimmed.match(/^(\d+)\.\s+(.+)$/);
    if (headingMatch) {
      flushList();
      blocks.push({ type: "heading", text: trimmed });
      continue;
    }

    if (/^\s*-\s+/.test(trimmed)) {
      listItems.push(trimmed.replace(/^\s*-\s+/, ""));
      continue;
    }

    flushList();
    blocks.push({ type: "paragraph", text: trimmed.trim() });
  }

  flushList();
  return blocks;
}

export function readVideoRulesDocument(): string {
  if (typeof window === "undefined") return DEFAULT_VIDEO_RULES_DOCUMENT;
  try {
    const raw = window.localStorage.getItem(VIDEO_RULES_STORAGE_KEY);
    if (typeof raw === "string" && raw.trim()) return raw;
  } catch {
    /* ignore */
  }
  return DEFAULT_VIDEO_RULES_DOCUMENT;
}

export function writeVideoRulesDocument(text: string): void {
  if (typeof window === "undefined") return;
  window.localStorage.setItem(VIDEO_RULES_STORAGE_KEY, text);
}

export function clearVideoRulesDocumentOverride(): void {
  if (typeof window === "undefined") return;
  window.localStorage.removeItem(VIDEO_RULES_STORAGE_KEY);
}
